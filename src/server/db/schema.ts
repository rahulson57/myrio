// ---------------------------------------------------------------------------
// conversations / conversation_participants / messages
// ---------------------------------------------------------------------------
export const conversations = sqliteTable('conversations', {
  id: idColumn(),
  // Canonical uniqueness key: min(user_a,user_b) || ':' || max(user_a,user_b)
  // — makes "message this author" idempotent (SPEC-002).
  pairKey: text('pair_key').notNull().unique(),
  createdAt: integer('created_at').notNull(),
  lastMessageAt: integer('last_message_at'),
});

export const conversationParticipants = sqliteTable(
  'conversation_participants',
  {
    conversationId: text('conversation_id')
      .notNull()
      .references(() => conversations.id, { onDelete: 'cascade' }),
    userId: text('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    lastReadAt: integer('last_read_at'),
  },
  (table) => [primaryKey({ columns: [table.conversationId, table.userId] })],
);

export const messages = sqliteTable(
  'messages',
  {
    id: idColumn(),
    conversationId: text('conversation_id')
      .notNull()
      .references(() => conversations.id, { onDelete: 'cascade' }),
    senderId: text('sender_id')
      .notNull()
      .references(() => users.id),
    bodyText: text('body_text').notNull(),
    createdAt: integer('created_at').notNull(),
  },
  (table) => [index('idx_messages_conv').on(table.conversationId, desc(table.createdAt))],
);

